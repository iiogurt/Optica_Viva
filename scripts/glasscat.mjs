// Generates js/lib/glasscat.js from a clone of the refractiveindex.info database (CC0):
//   git clone --depth 1 https://github.com/polyanskiy/refractiveindex.info-database.git
//   node scripts/glasscat.mjs <path to the clone>
// Takes the three-term Sellmeier fits (formula 2) of the makers' Zemax catalogues: SCHOTT N- and P-
// glasses (not the radiation-resistant or high-transmission variants), OHARA S- glasses marked
// "Recommended", and CDGM H- glasses.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2];
if (!root) { console.error('usage: node scripts/glasscat.mjs <refractiveindex.info-database clone>'); process.exit(1); }
const specs = join(root, 'database/data/specs');
const SETS = [
  { maker: 'SCHOTT', dir: 'schott/optical', keep: (n) => /^[NP]-/.test(n) && !/(HT|HTi|HTultra|G\d\d)$/.test(n) },
  { maker: 'OHARA', dir: 'ohara/optical', keep: (n, text) => /^S-/.test(n) && /Recommended/.test(text) },
  { maker: 'CDGM', dir: 'cdgm/optical', keep: (n) => /^H-/.test(n) },
];
const out = [], sources = new Set();
for (const set of SETS) {
  for (const f of readdirSync(join(specs, set.dir)).filter((x) => x.endsWith('.yml') && x !== 'about.yml').sort()) {
    const name = f.slice(0, -4), text = readFileSync(join(specs, set.dir, f), 'utf8');
    if (!set.keep(name, text)) continue;
    const m = text.match(/type: formula 2\s+wavelength_range: ([\d.]+) ([\d.]+)\s+coefficients: ([^\n]+)/);
    if (!m) continue;
    const c = m[3].trim().split(/\s+/).map(Number);
    if (c.length !== 7 || c[0] !== 0) continue;
    const ref = text.match(/href="([^"]+\.agf)"/i);
    if (ref) sources.add(`${set.maker}: ${ref[1]}`);
    // the maker's catalogue n_d, V_d and ΔP_g,F, kept to check the fit (null when absent)
    const prop = (k) => { const x = text.match(new RegExp(`\\n\\s+${k}: ([-\\d.eE+]+)`)); return x ? +x[1] : null; };
    out.push(`  '${name}': ['${set.maker}', ${c[1]}, ${c[3]}, ${c[5]}, ${c[2]}, ${c[4]}, ${c[6]}, ${+m[1]}, ${+m[2]}, ${prop('nd')}, ${prop('Vd')}, ${prop('dPgF')}],`);
  }
}
const body = `// GENERATED by scripts/glasscat.mjs from the refractiveindex.info database (CC0, public domain),
// which reproduces the makers' Zemax catalogues:
${[...sources].map((s) => '//   ' + s).join('\n')}
// name: [maker, B1, B2, B3, C1, C2, C3 (µm²), λmin, λmax (µm), catalogue n_d, V_d, ΔP_g,F],\n// three-term Sellmeier
//   n²(λ) − 1 = Σ Bᵢ λ² / (λ² − Cᵢ).  ${out.length} glasses.
export const CATALOGUE = {
${out.join('\n')}
};
`;
writeFileSync(new URL('../js/lib/glasscat.js', import.meta.url), body);
console.log(out.length, 'glasses;', SETS.map((s) => `${s.maker} ${out.filter((l) => l.includes(`'${s.maker}'`)).length}`).join(', '));
