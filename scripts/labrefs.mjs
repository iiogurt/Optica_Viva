#!/usr/bin/env node
// The laboratories' reference lists, gathered for the catalogue: every js/modules/<id>.js passes one
// literal array to references([...]); this script copies them into js/lib/labrefs.js, so the
// catalogue can show a laboratory's references without loading the laboratory.
//   node scripts/labrefs.mjs          check that js/lib/labrefs.js is up to date (npm run check)
//   node scripts/labrefs.mjs --write  regenerate it
// A module whose references are not a single literal array of strings is an error, not skipped.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'js/lib/labrefs.js');

// the source text of the array passed to the first references( call, or null
function arrayText(src) {
  const i = src.indexOf('references([');
  if (i < 0) return null;
  let j = i + 'references('.length, depth = 0, quote = null;
  for (; j < src.length; j++) {
    const c = src[j];
    if (quote) { if (c === '\\') j++; else if (c === quote) quote = null; continue; }
    if (c === "'" || c === '"' || c === '`') { quote = c; continue; }
    if (c === '[') depth++;
    if (c === ']' && --depth === 0) break;
  }
  return src.slice(i + 'references('.length, j + 1);
}

export function collect() {
  const refs = {}, problems = [];
  for (const f of readdirSync(join(ROOT, 'js/modules')).filter((x) => x.endsWith('.js')).sort()) {
    const src = readFileSync(join(ROOT, 'js/modules', f), 'utf8'), id = f.slice(0, -3), txt = arrayText(src);
    if (txt === null) continue;
    if (src.indexOf('references([', src.indexOf('references([') + 1) >= 0) { problems.push(`${f}: more than one references([...]) call`); continue; }
    let list;
    // evaluated with no globals: anything but literal strings throws
    try { list = vm.runInNewContext('(' + txt + ')', Object.create(null), { timeout: 1000 }); } catch (e) { problems.push(`${f}: references are not a literal array (${e.message})`); continue; }
    if (!Array.isArray(list) || !list.length || list.some((x) => typeof x !== 'string')) { problems.push(`${f}: references must be a non-empty array of strings`); continue; }
    refs[id] = list;
  }
  return { refs, problems };
}

export function render(refs) {
  return `// Generated by scripts/labrefs.mjs from the references([...]) of every laboratory; do not edit.
// The catalogue shows them under the entries each laboratory simulates.
export const LAB_REFS = ${JSON.stringify(refs, null, 2)};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { refs, problems } = collect();
  if (problems.length) { console.error('labrefs: ' + problems.join('\n')); process.exit(1); }
  const text = render(refs);
  if (process.argv.includes('--write')) { writeFileSync(OUT, text); console.log(`labrefs: wrote ${Object.keys(refs).length} laboratories`); }
  else if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error('labrefs: js/lib/labrefs.js is out of date; run node scripts/labrefs.mjs --write'); process.exit(1); }
  else console.log(`labrefs: ${Object.keys(refs).length} laboratories' references up to date`);
}
